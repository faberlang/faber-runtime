//! GI2-4 — free-running greedy decode + agreement/first-divergence record tests.
//!
//! Families:
//! 1. **Record contract (§4.5)**: serialization round-trip + the committed
//!    run-record self-consistency check (schema, divergence-field `none`,
//!    first-diverging position == first token mismatch vs the embedded
//!    `TRACE_TOKENS`, token-level, never text-level).
//! 2. **Greedy-loop mechanics on the real oracle** (bounded prefix, default
//!    lane): 3 free-running positions from the 9 pinned prompt tokens match
//!    the trace head — proves the free-running loop (EOG-excluded argmax,
//!    prediction feedback, finite gate) is not masked by the teacher-forced
//!    window.
//! 3. **Full 256-token acceptance run** (`#[ignore]` — ~30 min in the debug
//!    test profile; opt-in like the numeric golden cross-check): the free-
//!    running decode over all 256 positions, byte-stable vs the committed
//!    run record, all finite, §4.5 divergence record correct. The committed
//!    record is generated by the env-gated emitter (`FABER_GI24_EMIT_RECORD=1`)
//!    and is what the record tests validate.
//!
//! Model-dependent tests follow the `tensor_view_test` / `cpu_oracle_test`
//! convention: skipped (with a loud note) when the pinned row is absent.

