// 3. Full 256-token acceptance run (opt-in; the committed record's source)
// ---------------------------------------------------------------------------

/// One-time emission of the committed run record (env-gated). Run with
/// `FABER_GI24_EMIT_RECORD=1` to (re)generate the record + manifest under
/// `testdata/gi2-4-greedy-record/`. The full 256-token free-running decode
/// takes ~20-40 min in the debug test profile (documented tool_latency).
#[test]
fn emit_greedy_record_when_requested() {
    let Some(bytes) = pinned_model_bytes() else {
        return;
    };
    if std::env::var_os("FABER_GI24_EMIT_RECORD").is_none() {
        eprintln!("set FABER_GI24_EMIT_RECORD=1 to (re)emit the committed greedy run record");
        return;
    }
    let view = build_pinned_view(&bytes);
    let oracle = CpuOracle::build(&view).expect("oracle build");
    let window = load_logp_window();
    let record = run_greedy(&oracle, &TRACE_TOKENS, window.as_deref()).expect("full greedy run");
    let dir = record_dir();
    std::fs::create_dir_all(&dir).expect("create record dir");
    let wire = record_to_json(&record);
    std::fs::write(dir.join("record.json"), wire).expect("write record");
    let manifest = build_manifest(&view, &record);
    std::fs::write(dir.join("manifest.json"), manifest).expect("write manifest");
    eprintln!(
        "wrote GI2-4 greedy run record to {}: {}",
        dir.display(),
        record.divergence_field()
    );
}

/// The committed record manifest: schema/model/trace provenance + hash
/// accounting.
fn build_manifest(view: &TensorView<'_>, record: &GreedyRunRecord) -> String {
    let mut root = BTreeMap::new();
    root.insert("schema".to_string(), Valor::from(RECORD_MANIFEST_SCHEMA));
    let mut model = BTreeMap::new();
    model.insert("sha256".to_string(), Valor::from(view.sha256_hex()));
    model.insert("bytes".to_string(), Valor::from(view.file_size() as i64));
    root.insert("model".to_string(), model.into());
    let mut trace = BTreeMap::new();
    trace.insert("schema".to_string(), Valor::from(TRACE_SCHEMA));
    trace.insert(
        "comparator_revision".to_string(),
        Valor::from(TRACE_COMPARATOR_REVISION),
    );
    trace.insert(
        "file_sha256".to_string(),
        Valor::from(TRACE_FILE_SHA256_HEX),
    );
    root.insert("trace".to_string(), trace.into());
    let wire = record_to_json(record);
    let mut entry = BTreeMap::new();
    entry.insert("file".to_string(), Valor::from("record.json"));
    entry.insert(
        "sha256".to_string(),
        Valor::from(hex(&sha256(wire.as_bytes()))),
    );
    entry.insert(
        "generated_token_count".to_string(),
        Valor::from(record.generated_tokens.len() as i64),
    );
    root.insert(
        "fixtures".to_string(),
        Valor::from(vec![Valor::from(entry)]),
    );
    let json = Json::from_object(root).expect("manifest JSON is valid");
    format!("{}\n", json.to_wire())
}

/// The full 256-token acceptance run (opt-in — ~20-40 min in the debug test
/// profile): free-running decode over all 256 positions, byte-identical to
/// the committed run record, all finite, §4.5 divergence record correct.
/// Run with `cargo nextest run -p faber-runtime -E 'test(greedy_256_run)'
/// --run-ignored all`.
#[test]
#[ignore = "full 256-token free-running decode (~20-40 min debug profile); the committed record is the default-lane evidence"]
fn greedy_256_run_matches_embedded_trace() {
    let Some(oracle) = shared_oracle() else {
        return;
    };
    let window = load_logp_window();
    let record = run_greedy(&oracle, &TRACE_TOKENS, window.as_deref()).expect("full greedy run");
    assert_eq!(record.generated_tokens.len(), GREEDY_TOKEN_COUNT);
    assert!(record.all_finite, "finite gate at every covered position");

    // Byte-stable vs the committed record (the run is deterministic).
    let wire = record_to_json(&record);
    let committed = std::fs::read_to_string(record_dir().join("record.json"))
        .expect("committed record must exist (emit with FABER_GI24_EMIT_RECORD=1)");
    assert_eq!(
        wire, committed,
        "the full run must be byte-identical to the committed record"
    );

    // §4.5: the record is taken at the FIRST diverging position, token-level.
    match &record.first_divergence {
        None => {
            assert!(
                record
                    .generated_tokens
                    .iter()
                    .zip(TRACE_TOKENS.iter())
                    .all(|(o, c)| o == c),
                "divergence field must be none only when the full trace agrees"
            );
            eprintln!("GI2-4 verdict: divergence field = none (all 256 generated tokens match the comparator trace)");
        }
        Some(d) => {
            let pos = d.position as usize;
            assert!(
                record.generated_tokens[pos] != TRACE_TOKENS[pos]
                    && record.generated_tokens[..pos]
                        .iter()
                        .zip(TRACE_TOKENS[..pos].iter())
                        .all(|(o, c)| o == c),
                "the record must be at the FIRST diverging position"
            );
            eprintln!(
                "GI2-4 verdict: {d} (all finite = {})",
                record.all_finite
            );
        }
    }
}
