/// Machine-local pinned row (skipped when absent — same convention as the
/// GI2-3 oracle tests).
const PINNED_MODEL_PATH: &str = "/Users/ianzepp/ai/models/SmolLM2-360M-Instruct-Q4_K_M.gguf";

/// The committed comparator logp reference window (17×49152 f32 LE,
/// position-major) — used only for the §4.3 band at a diverging position
/// inside the captured window; the same fixture the GI2-3 comparison pins.
const LOGP_REFERENCE_REL_PATH: &str =
    "../radix/docs/factory/gpu-inference-gguf/evidence/gi2-3-logp-reference.bin";
const LOGP_REFERENCE_SHA256_HEX: &str =
    "d105b49bde0ee5070020bb3a545578ba1195900937f44446893ad3bbaabad8ec";

/// Committed GI2-4 run record (Q3 default: crate-local testdata).
const RECORD_REL_DIR: &str = "testdata/gi2-4-greedy-record";

fn pinned_model_bytes() -> Option<Vec<u8>> {
    let path = std::path::Path::new(PINNED_MODEL_PATH);
    if !path.exists() {
        eprintln!("SKIP: pinned model not present at {PINNED_MODEL_PATH}");
        return None;
    }
    std::fs::read(path).ok()
}

fn record_dir() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(RECORD_REL_DIR)
}

fn build_pinned_view(bytes: &[u8]) -> TensorView<'_> {
    let admission = admit_gguf(bytes).expect("pinned row must admit");
    let view = TensorView::build(&admission, bytes).expect("view must build");
    assert!(view.coverage_ok(), "the pinned view must tile exactly");
    assert_eq!(view.sha256_hex(), PINNED_SHA256_HEX, "pinned row identity");
    view
}

fn shared_oracle() -> Option<&'static CpuOracle> {
    static ORACLE: std::sync::OnceLock<Option<CpuOracle>> = std::sync::OnceLock::new();
    ORACLE
        .get_or_init(|| {
            if !std::path::Path::new(PINNED_MODEL_PATH).exists() {
                eprintln!("SKIP: pinned model not present at {PINNED_MODEL_PATH}");
                return None;
            }
            let bytes = std::fs::read(PINNED_MODEL_PATH).expect("pinned model read");
            let bytes: &'static [u8] = Box::leak(bytes.into_boxed_slice());
            let view = build_pinned_view(bytes);
            Some(CpuOracle::build(&view).expect("oracle build"))
        })
        .as_ref()
}

/// Load the committed comparator logp window (17×49152 f32 LE), skipping
/// loudly when the sibling radix layout moved.
fn load_logp_window() -> Option<Vec<f32>> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(LOGP_REFERENCE_REL_PATH);
    let bytes = match std::fs::read(&path) {
        Ok(bytes) => bytes,
        Err(err) => {
            eprintln!(
                "SKIP: comparator logp reference not readable at {} ({err})",
                path.display()
            );
            return None;
        }
    };
    assert_eq!(
        hex(&sha256(&bytes)),
        LOGP_REFERENCE_SHA256_HEX,
        "logp reference fixture must be hash-pinned"
    );
    assert_eq!(bytes.len(), WINDOW_POSITIONS * VOCAB_SIZE * 4);
    Some(
        bytes
            .chunks_exact(4)
            .map(|c| f32::from_le_bytes([c[0], c[1], c[2], c[3]]))
            .collect(),
    )
}

// -- Valor walking helpers (same pattern as cpu_oracle_test) ----------------

fn text(v: &Valor) -> &str {
    let Valor::Textus(s) = v else {
        panic!("expected JSON string")
    };
    s
}

fn int(v: &Valor) -> i64 {
    let Valor::Numerus(n) = v else {
        panic!("expected JSON integer")
    };
    *n
}

fn flag(v: &Valor) -> bool {
    let Valor::Bivalens(b) = v else {
        panic!("expected JSON boolean")
    };
    *b
}

fn list<'a>(v: &'a Valor) -> &'a [Valor] {
    let Valor::Lista(items) = v else {
        panic!("expected JSON array")
    };
    items
}

fn field<'a>(v: &'a Valor, key: &str) -> &'a Valor {
    let Valor::Tabula(fields) = v else {
        panic!("expected JSON object")
    };
    fields
        .get(key)
        .unwrap_or_else(|| panic!("missing JSON field {key:?}"))
}

// ---------------------------------------------------------------------------
// 1. Record contract (§4.5): serialization round-trip + committed record
// ---------------------------------------------------------------------------

#[test]
fn record_serialization_round_trips_and_divergence_field() {
    // Serialize a synthetic record, parse it back, and verify every §4.5
    // field survives. No model needed.
    let record = GreedyRunRecord {
        generated_tokens: TRACE_TOKENS[..16].to_vec(),
        all_finite: true,
        first_divergence: Some(GreedyDivergence {
            position: 3,
            comparator_trace_token: TRACE_TOKENS[3],
            oracle_token: 9,
            failing_thresholds: vec![FailingThreshold::Top1, FailingThreshold::Band],
            max_band_deviation: Some(2.1e-2),
        }),
    };
    let wire = record_to_json(&record);
    let root = Json::parse(&wire).expect("record parses").as_valor().clone();
    assert_eq!(text(field(&root, "schema")), RECORD_SCHEMA);
    assert_eq!(int(field(&root, "generated_token_count")), 16);
    assert_eq!(flag(field(&root, "all_finite")), true);
    assert_eq!(flag(field(&root, "all_agree")), false);
    assert_eq!(list(field(&root, "generated_tokens")).len(), 16);

    let div = field(&root, "first_divergence");
    let is_tabula = matches!(div, Valor::Tabula(_));
    assert!(is_tabula, "first_divergence must be an object, got {div:?}");
    assert_eq!(int(field(div, "position")), 3);
    assert_eq!(int(field(div, "comparator_trace_token")), TRACE_TOKENS[3]);
    assert_eq!(int(field(div, "oracle_token")), 9);
    let failing_thresholds = list(field(div, "failing_thresholds"));
    assert_eq!(failing_thresholds.len(), 2);
    assert_eq!(text(&failing_thresholds[0]), "top-1");
    assert_eq!(text(&failing_thresholds[1]), "band");
    // The divergence field (human readout) is token-level, never text-level.
    assert!(record.divergence_field().starts_with("position 3"));

    // A fully-agreeing record has divergence field `none`.
    let ok = GreedyRunRecord {
        generated_tokens: TRACE_TOKENS[..4].to_vec(),
        all_finite: true,
        first_divergence: None,
    };
    let wire_ok = record_to_json(&ok);
    let root_ok = Json::parse(&wire_ok).expect("ok record parses").as_valor().clone();
    assert!(matches!(field(&root_ok, "first_divergence"), Valor::Nihil));
    assert_eq!(ok.divergence_field(), "none");
}

#[test]
fn committed_greedy_record_is_schema_valid_and_self_consistent() {
    // The committed run record (the GI2-4 receipt) must be present, match
    // its schema, and be self-consistent with the embedded trace: the
    // first-diverging position is exactly the first token mismatch between
    // the committed generated tokens and TRACE_TOKENS, the divergence field
    // is `none` exactly when the full trace agrees, and the finite gate
    // holds. When the record is absent (the full 256-token run is an opt-in
    // ~25-min compute), this skips loudly — the record fixture is required
    // for the strict assertion, exactly like the pinned-model skip.
    let dir = record_dir();
    let wire = match std::fs::read_to_string(dir.join("record.json")) {
        Ok(wire) => wire,
        Err(err) => {
            eprintln!(
                "SKIP: committed greedy run record absent at {} ({err}); emit it with FABER_GI24_EMIT_RECORD=1 (full 256-token run, ~25 min debug profile)",
                dir.display(),
            );
            return;
        }
    };
    let root = Json::parse(&wire).expect("record parses").as_valor().clone();

    assert_eq!(text(field(&root, "schema")), RECORD_SCHEMA);
    let n = int(field(&root, "generated_token_count"));
    assert_eq!(n, GREEDY_TOKEN_COUNT as i64, "the committed record is the full 256-token run");

    let generated: Vec<i64> = list(field(&root, "generated_tokens"))
        .iter()
        .map(int)
        .collect();
    assert_eq!(generated.len(), GREEDY_TOKEN_COUNT);
    assert!(
        generated.iter().all(|&t| (0..VOCAB_SIZE as i64).contains(&t)),
        "all generated token ids must be in [0, vocab_size)"
    );

    // The first token mismatch vs the embedded trace defines the §4.5 record.
    let first_mismatch = generated
        .iter()
        .zip(TRACE_TOKENS.iter())
        .position(|(o, c)| o != c);
    let all_agree = first_mismatch.is_none();
    assert_eq!(
        flag(field(&root, "all_agree")),
        all_agree,
        "all_agree must equal (no token mismatch vs the trace)"
    );

    match field(&root, "first_divergence") {
        Valor::Nihil => {
            assert!(all_agree, "divergence field must be none only when the full trace agrees");
        }
        div => {
            let pos = int(field(div, "position"));
            assert_eq!(Some(pos as usize), first_mismatch, "the record is taken at the FIRST diverging position");
            assert_eq!(
                int(field(div, "comparator_trace_token")),
                TRACE_TOKENS[pos as usize],
                "record carries the comparator trace token"
            );
            assert_eq!(
                int(field(div, "oracle_token")),
                generated[pos as usize],
                "record carries the oracle token"
            );
            let failing: Vec<String> = list(field(div, "failing_thresholds"))
                .iter()
                .map(text)
                .map(ToOwned::to_owned)
                .collect();
            assert!(
                !failing.is_empty(),
                "failing thresholds must be named at a divergence"
            );
            // Band deviation is only inside the captured 17-position window.
            if pos < WINDOW_POSITIONS as i64 {
                assert!(
                    matches!(field(div, "max_band_deviation"), Valor::Fractus(_)),
                    "band deviation must be recorded inside the captured window (pos {pos})"
                );
            } else {
                assert!(
                    matches!(field(div, "max_band_deviation"), Valor::Nihil),
                    "band deviation must be absent beyond the captured window (pos {pos})"
                );
            }
        }
    }
    assert_eq!(flag(field(&root, "all_finite")), true, "finite gate must hold");

    // The trace provenance is hash-accounted in the committed record.
    let trace = field(&root, "trace");
    assert_eq!(text(field(trace, "schema")), TRACE_SCHEMA);
    assert_eq!(text(field(trace, "file_sha256")), TRACE_FILE_SHA256_HEX);
}

// ---------------------------------------------------------------------------
// 2. Greedy-loop mechanics on the real oracle (bounded prefix, default lane)
// ---------------------------------------------------------------------------

#[test]
fn greedy_loop_short_prefix_is_free_running_and_matches_trace_head() {
    let Some(oracle) = shared_oracle() else {
        return;
    };
    // 3 free-running positions: the prediction is fed back (never
    // teacher-forced), EOG {0,2} excluded, finite gate checked.
    let record = run_greedy(oracle, &TRACE_TOKENS[..3], None).expect("greedy run");
    assert_eq!(record.generated_tokens.len(), 3);
    assert_eq!(
        record.generated_tokens,
        [TRACE_TOKENS[0], TRACE_TOKENS[1], TRACE_TOKENS[2]],
        "the free-running greedy head must match the pinned trace head (top-1 exact, GI2-3)"
    );
    assert!(record.all_finite, "finite gate at every covered position");
    assert_eq!(record.first_divergence, None, "no divergence in the prefix");
    assert_eq!(record.divergence_field(), "none");

    // The prefix run is genuinely free-running: the second generated token
    // comes from feeding the first prediction, not from the trace.
    let mut run = ForwardRun::new(oracle, &PROMPT_TOKENS).expect("run");
    let first_logits = run.position_logits().expect("position 0");
    let first = top1_non_eog(&first_logits, &EOG_TOKENS);
    assert_eq!(first, TRACE_TOKENS[0]);
    run.push_token(first).expect("feed own prediction");
    let second_logits = run.position_logits().expect("position 1");
    let second = top1_non_eog(&second_logits, &EOG_TOKENS);
    assert_eq!(second, TRACE_TOKENS[1]);
    assert_eq!(
        record.generated_tokens[1], second,
        "greedy loop must feed its own prediction"
    );
}

